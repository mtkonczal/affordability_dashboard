#!/usr/bin/env python3
"""Freeze dashboard series into standalone chart iframes for one blog post.

    python3 scripts/snapshot_embed.py embeds/rising-cost-2026/config.json

The config lives in the post's folder, embeds/<slug>/config.json, so the
choices behind a published chart stay next to it:

    {
      "start": "2024-12",                  default window start for every chart
      "charts": [
        {"id": "mortgage", "title": "30-Year Mortgage Rate",
         "series": ["mortgage"],           ids from data/app_data.js
         "start": "2024-12-26",            optional per-chart start / end
         "end": "2026-10-15"},
        {"id": "aca-premium", "series": ["aca_benchmark_premium"],
         "start": "2000",                  whole history on the chart...
         "headline_from": "2025"},         ...but the change is measured from 2025
        {"id": "gas-diesel", "title": "Gasoline and Diesel",
         "series": ["gas", "diesel"],      two lines on one chart: same units
         "labels": ["Gasoline", "Diesel"]} optional line names
      ],
      "graphics": {"Graphic 1": ["mortgage", "gas-diesel"]}   one iframe each
    }

Writes, next to the config:
  data.js     window.EMBED_DATA, every chart's series cut to its window, plus
              the vintage of the payload they came from
  chart.html  a copy of embeds/template/chart.html (copied, not linked, so a
              later edit to the template can't change a published post)
  README.md   one iframe snippet per graphic; its charts sit side by side

Window rule: a reading is kept if its date falls inside [start, end]. A start
or end may be a year (2025), a month (2024-12) or a day (2024-12-26); a year or
month covers the whole period, so "end": "2026-10" keeps every October reading.
Annual series are dated Jan 1 of their year, so an ACA window starting 2024-12
begins at the 2025 plan year. Quarterly series are dated the first month of
the quarter, so a 2024-12 start drops Q4 2024 (dated 2024-10-01).

The snapshot is read from the committed data/app_data.js, never refetched, so
it carries that file's vintage. Nothing in the automated refresh touches
embeds/: these charts stay as they were on publication, through later
revisions. Re-run only before the post goes out.
"""
import json
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
APP_DATA = ROOT / "data" / "app_data.js"
TEMPLATE = ROOT / "embeds" / "template" / "chart.html"
PAGES_BASE = "https://www.mikekonczal.com/affordability_dashboard"
SANDBOX = "allow-scripts allow-downloads allow-popups"

# Fields the chart page reads. Everything else in the payload stays behind.
KEEP = ["id", "label", "category", "units", "fred_id", "source_note",
        "source_url", "rebase"]


def load_app_data():
    src = APP_DATA.read_text(encoding="utf-8")
    m = re.search(r"Auto-generated by fetch_data\.R on (\d{4}-\d{2}-\d{2})", src)
    body = src[src.index("window.AFFORDABILITY_DATA"):]
    body = body[body.index("=") + 1:].strip().rstrip(";")
    return json.loads(body), (m.group(1) if m else None)


def bound(s, is_end):
    """'2025' / '2024-12' / '2024-12-26' -> an inclusive YYYY-MM-DD bound."""
    if not isinstance(s, str) or not re.match(r"^\d{4}(-\d{2}(-\d{2})?)?$", s):
        sys.exit(f"bad date bound {s!r}: use YYYY, YYYY-MM or YYYY-MM-DD")
    if len(s) == 4:
        return s + ("-12-31" if is_end else "-01-01")
    if len(s) == 7:
        return s + ("-31" if is_end else "-01")
    return s


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__.split("\n\n")[1])
    cfg_path = Path(sys.argv[1]).resolve()
    cfg = json.loads(cfg_path.read_text(encoding="utf-8"))
    out = cfg_path.parent
    slug = out.name
    if out.parent != ROOT / "embeds" or slug == "template":
        sys.exit("config must be embeds/<slug>/config.json")

    data, vintage = load_app_data()
    if not vintage:
        sys.exit("could not read the vintage line from data/app_data.js")

    charts = {}
    for ch in cfg["charts"]:
        cid = ch["id"]
        if not re.match(r"^[a-z0-9][a-z0-9-]*$", cid) or cid in charts:
            sys.exit(f"bad or duplicate chart id {cid!r}")
        start = ch.get("start", cfg.get("start"))
        end = ch.get("end")
        lo, hi = bound(start, False), bound(end, True) if end else "9999-12-31"
        labels = ch.get("labels", [])
        lines = []
        for i, sid in enumerate(ch["series"]):
            if sid not in data:
                sys.exit(f"{cid}: unknown series id {sid!r}; see data/manifest.json")
            item = data[sid]
            pts = [p for p in item["data"]
                   if lo <= p["date"] <= hi and p.get("value") is not None]
            # Fail loudly: a one-point window draws an empty chart, which is
            # what the Census annual series (last reading 2024) do from Dec 2024.
            if len(pts) < 2:
                sys.exit(f"{cid}/{sid}: only {len(pts)} reading(s) in [{lo}, {hi}] "
                         f"(latest is {item['data'][-1]['date']})")
            s = {k: item[k] for k in KEEP if k in item}
            if i < len(labels):
                s["label"] = labels[i]
            s["data"] = pts
            lines.append(s)
            print(f"  {cid:14s} {sid:22s} {len(pts):4d} obs  "
                  f"{pts[0]['date']} {pts[0]['value']} -> {pts[-1]['date']} {pts[-1]['value']}")
        # One y-axis per chart, so lines that share it must share units, and
        # either all plot as % change (index series) or all as levels.
        if len({l["units"] for l in lines}) > 1 or len({bool(l.get("rebase")) for l in lines}) > 1:
            sys.exit(f"{cid}: series have different units; they can't share one axis")
        # headline_from: measure the change from a later reading than the
        # chart's first, so a long history can carry the post's own figure.
        hf = ch.get("headline_from")
        if hf:
            hb = bound(hf, False)
            for l in lines:
                if not any(p["date"] >= hb for p in l["data"][:-1]):
                    sys.exit(f"{cid}: headline_from {hf} leaves no change to measure for {l['id']}")
        charts[cid] = {"id": cid, "title": ch.get("title", lines[0]["label"]),
                       "start": start, "end": end, "headline_from": hb if hf else None,
                       "series": lines}

    groups = cfg.get("graphics") or {"Charts": list(charts)}
    for name, ids in groups.items():
        missing = [c for c in ids if c not in charts]
        if missing:
            sys.exit(f"graphics[{name!r}] lists unknown chart(s) {missing}")

    payload = {"slug": slug, "vintage": vintage, "charts": charts, "graphics": groups}
    (out / "data.js").write_text(
        f"// Frozen snapshot for embeds/{slug}, taken from data/app_data.js "
        f"(fetch_data.R run of {vintage}).\n"
        f"// Written by scripts/snapshot_embed.py from config.json. Do not hand-edit.\n"
        f"window.EMBED_DATA = {json.dumps(payload, ensure_ascii=False)};\n",
        encoding="utf-8")
    shutil.copyfile(TEMPLATE, out / "chart.html")

    md = [f"# Embeds: {slug}", "",
          f"Frozen from the {vintage} data refresh by `scripts/snapshot_embed.py`.",
          "Paste each snippet into its own WordPress Custom HTML block. The charts",
          "in a graphic sit side by side inside the one iframe; on phones they",
          "become a sideways-swipe row at the same height.", ""]
    for name, ids in groups.items():
        url = f"{PAGES_BASE}/embeds/{slug}/chart.html?ids={','.join(ids)}"
        titles = ", ".join(charts[c]["title"] for c in ids)
        md += [f"## {name}", "", titles, "", "```html",
               f'<iframe src="{url}" title="{name}: {titles}" '
               f'style="width:100%; height:420px; border:0;" '
               f'sandbox="{SANDBOX}" loading="lazy"></iframe>', "```", ""]
    (out / "README.md").write_text("\n".join(md), encoding="utf-8")
    print(f"wrote embeds/{slug}/ (data.js, chart.html, README.md)")


if __name__ == "__main__":
    main()
